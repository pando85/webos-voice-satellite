//! Generates the ESPHome native API protobuf types from the vendored
//! `proto/api.proto` with `protox` (pure Rust, no `protoc` needed) and
//! `prost-build`, plus a table of message type ids.
//!
//! prost ignores custom options, so the `option (id) = N;` message type ids are
//! extracted from the proto text here and emitted as `ApiMessage` impls.

use std::fmt::Write as _;
use std::path::PathBuf;

const PROTO_DIR: &str = "proto";
const API_PROTO: &str = "proto/api.proto";

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed={API_PROTO}");
    println!("cargo:rerun-if-changed={PROTO_DIR}/api_options.proto");
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);

    let mut fds = protox::Compiler::new([PROTO_DIR])?
        .include_imports(true)
        .open_files(["api.proto"])?
        .file_descriptor_set();
    // descriptor.proto is only needed for the custom option declarations.
    fds.file
        .retain(|f| f.name() != "google/protobuf/descriptor.proto");

    let mut config = prost_build::Config::new();
    config.out_dir(&out_dir);
    // Proto comments contain indented text that rustdoc would run as doctests.
    config.disable_comments(["."]);
    config.compile_fds(fds)?;

    let ids = message_ids(&std::fs::read_to_string(API_PROTO)?)?;
    let mut out = String::from("// @generated by build.rs from proto/api.proto\n");
    for (name, id) in &ids {
        writeln!(
            out,
            "impl crate::proto::ApiMessage for {name} {{ const ID: u16 = {id}; const NAME: &'static str = \"{name}\"; }}"
        )?;
    }
    out.push_str("/// Returns the proto message name for a message type id.\n");
    out.push_str(
        "#[must_use]\npub fn message_name(id: u16) -> Option<&'static str> {\n    match id {\n",
    );
    for (name, id) in &ids {
        writeln!(out, "        {id} => Some(\"{name}\"),")?;
    }
    out.push_str("        _ => None,\n    }\n}\n");
    std::fs::write(out_dir.join("message_ids.rs"), out)?;
    Ok(())
}

/// Returns `(RustTypeName, id)` for each top-level message with an `(id)` option.
fn message_ids(proto: &str) -> Result<Vec<(String, u16)>, String> {
    let mut ids = Vec::new();
    let mut current: Option<String> = None;
    let mut depth = 0_i32;
    for raw in proto.lines() {
        let line = raw.split("//").next().unwrap_or("").trim();
        if depth == 0 {
            if let Some(rest) = line.strip_prefix("message ") {
                let name = rest
                    .split(|c: char| c == '{' || c.is_whitespace())
                    .next()
                    .unwrap_or("");
                current = Some(name.to_owned());
            }
        }
        let compact: String = line.chars().filter(|c| !c.is_whitespace()).collect();
        if depth == 1 {
            if let (Some(name), Some(rest)) = (&current, compact.strip_prefix("option(id)=")) {
                let num = rest.trim_end_matches(';');
                let id: u16 = num
                    .parse()
                    .map_err(|e| format!("bad id {num:?} for {name}: {e}"))?;
                ids.push((rust_type_name(name), id));
            }
        }
        depth += i32::try_from(line.matches('{').count()).unwrap_or(0);
        depth -= i32::try_from(line.matches('}').count()).unwrap_or(0);
        if depth == 0 {
            current = None;
        }
    }
    if ids.len() < 100 {
        return Err(format!(
            "only {} message ids found; parser out of date?",
            ids.len()
        ));
    }
    Ok(ids)
}

/// prost's upper camel case conversion for message names (e.g. `GATT` -> `Gatt`).
fn rust_type_name(s: &str) -> String {
    // Mirrors heck's UpperCamelCase as used by prost-build: split into words on
    // case boundaries, then capitalise the first letter of each word only.
    let chars: Vec<char> = s.chars().collect();
    let mut words: Vec<String> = Vec::new();
    let mut word = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c == '_' {
            if !word.is_empty() {
                words.push(std::mem::take(&mut word));
            }
            continue;
        }
        let prev = if i > 0 { Some(chars[i - 1]) } else { None };
        let next = chars.get(i + 1).copied();
        let boundary = match prev {
            Some(p) if c.is_uppercase() => {
                p.is_lowercase()
                    || p.is_ascii_digit()
                    || (p.is_uppercase() && next.is_some_and(char::is_lowercase))
            }
            _ => false,
        };
        if boundary && !word.is_empty() {
            words.push(std::mem::take(&mut word));
        }
        word.push(c);
    }
    if !word.is_empty() {
        words.push(word);
    }
    words
        .iter()
        .map(|w| {
            let mut cs = w.chars();
            cs.next().map_or_else(String::new, |f| {
                f.to_uppercase().collect::<String>() + &cs.as_str().to_lowercase()
            })
        })
        .collect()
}
